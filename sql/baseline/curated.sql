CREATE OR REPLACE PROCEDURE SF360.CURATED.SP_REFRESH_CURATED()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
BEGIN
  ALTER SESSION SET TIMEZONE = ''UTC'';
  -- Dimensions first
  ALTER DYNAMIC TABLE SF360.CURATED.DIM_ACCOUNT REFRESH;
  ALTER DYNAMIC TABLE SF360.CURATED.DIM_SERVICE_TYPE REFRESH;
  ALTER DYNAMIC TABLE SF360.CURATED.DIM_DATE REFRESH;
  -- Rates before anything that prices
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_RATE_EFFECTIVE REFRESH;
  -- Facts
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_DAILY_CREDITS REFRESH;
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_DAILY_CURRENCY REFRESH;
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_QUERY_ATTRIBUTION REFRESH;
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_ANOMALY_DAILY REFRESH;
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_OPTIMIZATION_OPPORTUNITY REFRESH;
  -- Contract position depends on currency and dim_date; projection depends on position
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_CONTRACT_POSITION REFRESH;
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_CONTRACT_PROJECTION REFRESH;
  -- Freshness last so it records the completed state
  ALTER DYNAMIC TABLE SF360.CURATED.FCT_FRESHNESS REFRESH;
  RETURN ''SP_REFRESH_CURATED complete'';
END;
';
