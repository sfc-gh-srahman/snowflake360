  o.LOWER_BOUND_FLOORED         AS LOWER_BOUND,
  o.UPPER_BOUND,
  (o.FORECASTED_VALUE_RAW < 0)  AS NATIVE_FORECAST_WAS_NEGATIVE,
  o.ACTUAL_VALUE - o.FORECASTED_VALUE_FLOORED AS VARIANCE_VS_FORECAST,
  CURRENT_TIMESTAMP()           AS BUILT_AT
FROM SF360.LANDING.LND_ORG_ANOMALIES o

UNION ALL

SELECT
  'ACCOUNT',
  d.ACCOUNT_KEY, a.ACCOUNT_NAME, d.REGION,
  a.ANOMALY_DATE, a.ANOMALY_ID, a.IS_ANOMALY,
