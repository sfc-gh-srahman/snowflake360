create or replace view SF360.CURATED.FCT_BILLING_PERIOD_POSITION(
	CONTRACT_SK,
	CONTRACT_NUMBER,
	CURRENCY,
	BILLING_FREQUENCY,
	CADENCE_MONTHS,
	PERIOD_COUNT,
