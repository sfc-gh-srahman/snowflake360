  SELECT AVG(GREATEST(FORECASTED_VALUE_RAW, 0)) AS RATE_PER_DAY
  FROM SF360.LANDING.LND_ORG_ANOMALIES
  WHERE ANOMALY_DATE > DATEADD('day', -30, (SELECT AS_OF FROM latest))
),
