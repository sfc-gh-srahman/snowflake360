  (u.CUME_DOLLARS > c.CAPACITY_PURCHASED)      AS IS_PAST_CAPACITY,
  DATEDIFF('day', u.USAGE_DATE_UTC, c.CONTRACT_END_DATE) AS DAYS_REMAINING_IN_TERM,
  c.CONTRACT_SOURCE,
  CURRENT_TIMESTAMP()                          AS BUILT_AT
FROM cume u CROSS JOIN c;
