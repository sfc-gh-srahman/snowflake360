WITH c AS (
  SELECT * FROM SF360.CONFIG.CONTRACT WHERE VALID_TO IS NULL AND IS_ACTIVE
),
as_of AS (
  -- Exclude the in-progress day: currency for today is partial
  SELECT DATEADD('day', -1, MAX(USAGE_DATE_UTC)) AS MAX_CLOSED_DATE
  FROM SF360.CURATED.FCT_DAILY_CURRENCY
),
daily AS (
  SELECT f.USAGE_DATE_UTC,
         SUM(f.NET_IN_CURRENCY)       AS DOLLARS_DAY,
         SUM(f.COMMITTED_IN_CURRENCY) AS COMMITTED_DAY,
         SUM(f.OVERAGE_IN_CURRENCY)   AS OVERAGE_DAY,
         COUNT(DISTINCT f.ACCOUNT_KEY) AS ACCOUNTS_WITH_SPEND
  FROM SF360.CURATED.FCT_DAILY_CURRENCY f
  CROSS JOIN c
  WHERE f.USAGE_DATE_UTC BETWEEN c.CONTRACT_START_DATE AND c.CONTRACT_END_DATE
    AND f.USAGE_DATE_UTC <= (SELECT MAX_CLOSED_DATE FROM as_of)
  GROUP BY 1
),
spine AS (
  SELECT d.DATE_UTC AS USAGE_DATE_UTC,
         COALESCE(dd.DOLLARS_DAY,0)   AS DOLLARS_DAY,
         COALESCE(dd.COMMITTED_DAY,0) AS COMMITTED_DAY,
         COALESCE(dd.OVERAGE_DAY,0)   AS OVERAGE_DAY,
         COALESCE(dd.ACCOUNTS_WITH_SPEND,0) AS ACCOUNTS_WITH_SPEND
  FROM SF360.CURATED.DIM_DATE d
  CROSS JOIN c
  LEFT JOIN daily dd ON dd.USAGE_DATE_UTC = d.DATE_UTC
  WHERE d.DATE_UTC BETWEEN c.CONTRACT_START_DATE AND c.CONTRACT_END_DATE
    AND d.DATE_UTC <= (SELECT MAX_CLOSED_DATE FROM as_of)
),
cume AS (
  SELECT USAGE_DATE_UTC, DOLLARS_DAY, COMMITTED_DAY, OVERAGE_DAY, ACCOUNTS_WITH_SPEND,
