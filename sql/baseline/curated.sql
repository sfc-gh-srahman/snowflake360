  c.CONTRACT_NUMBER,
  u.USAGE_DATE_UTC,
  c.CONTRACT_START_DATE,
  c.CONTRACT_END_DATE,
  c.CAPACITY_PURCHASED,
  c.METERED_CURRENCY,
  u.DOLLARS_DAY,
  u.COMMITTED_DAY,
  u.OVERAGE_DAY,
  u.ACCOUNTS_WITH_SPEND,
  u.DAY_INDEX,
  u.CUME_DOLLARS                               AS CAPACITY_USED,
  -- A360 capacity formula. All addends customer-entered except CAPACITY_USED.
  u.CUME_DOLLARS + c.TOTAL_FREE_USAGE + c.ROLLOVER + c.ADJUSTMENT + c.BALANCE_TRANSFER
    + c.CURRENCY_CONVERSION_ADJUSTMENT + c.DATA_SHARING_REBATE + c.BALANCE_MIGRATION
                                               AS TOTAL_CAPACITY_USED,
  c.CAPACITY_PURCHASED - (u.CUME_DOLLARS + c.TOTAL_FREE_USAGE + c.ROLLOVER + c.ADJUSTMENT
    + c.BALANCE_TRANSFER + c.CURRENCY_CONVERSION_ADJUSTMENT + c.DATA_SHARING_REBATE
