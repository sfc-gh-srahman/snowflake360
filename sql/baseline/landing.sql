CREATE OR REPLACE PROCEDURE SF360.LANDING.SP_REBUILD_LANDING()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
DECLARE
  retention NUMBER;
  msg VARCHAR DEFAULT '''';
BEGIN
  -- Docs mandate UTC for reconciling ACCOUNT_USAGE against ORGANIZATION_USAGE
  ALTER SESSION SET TIMEZONE = ''UTC'';
  SELECT TO_NUMBER(SETTING_VALUE) INTO :retention
    FROM SF360.CONFIG.SETTINGS WHERE SETTING_KEY = ''RETENTION_DAYS'';

  -- Org object inventory
  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ORG_ACCOUNTS AS
    SELECT ORGANIZATION_NAME, ACCOUNT_NAME, ACCOUNT_LOCATOR, REGION, REGION_GROUP, EDITION,
           CREATED_ON, DELETED_ON, MOVED_ON, ALTERED_ON, IS_ORG_ADMIN, IS_LOCKED,
           IS_MANAGED, MANAGED_ACCOUNTS, PARENT_ACCOUNT, ACCOUNT_URL, COMMENT,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ORGANIZATION_USAGE.ACCOUNTS;

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ORG_SERVICE_TYPES AS
    SELECT SERVICE_TYPE, RATING_TYPE, COUNT(*) AS RATE_ROWS, MAX(DATE) AS LAST_SEEN,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ORGANIZATION_USAGE.RATE_SHEET_DAILY
    WHERE DATE >= DATEADD(''day'', -90, CURRENT_DATE())
    GROUP BY SERVICE_TYPE, RATING_TYPE;

  msg := ''org inventory ok; '';

  -- Org scoped history. Bounded time, explicit columns, account filter per docs.
  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ORG_RATE_SHEET AS
    WITH scope AS (SELECT ACCOUNT_NAME FROM SF360.CONFIG.ACCOUNT_SCOPE WHERE IS_INCLUDED),
         se AS (SELECT (COUNT(*)=0) AS ALL_ACCT FROM scope)
    SELECT r.DATE AS RATE_DATE, r.ORGANIZATION_NAME, r.CONTRACT_NUMBER, r.ACCOUNT_NAME,
           r.ACCOUNT_LOCATOR, r.REGION, r.ACCOUNT_LOCATOR || ''|'' || r.REGION AS ACCOUNT_KEY,
           r.SERVICE_LEVEL, r.USAGE_TYPE, r.SERVICE_TYPE, r.RATING_TYPE, r.BILLING_TYPE,
           r.CURRENCY, r.EFFECTIVE_RATE, r.IS_ADJUSTMENT, CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ORGANIZATION_USAGE.RATE_SHEET_DAILY r CROSS JOIN se
    WHERE r.DATE >= DATEADD(''day'', -:retention, CURRENT_DATE())
      AND (se.ALL_ACCT OR r.ACCOUNT_NAME IN (SELECT ACCOUNT_NAME FROM scope));

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ORG_CURRENCY_DAILY AS
    WITH scope AS (SELECT ACCOUNT_NAME FROM SF360.CONFIG.ACCOUNT_SCOPE WHERE IS_INCLUDED),
         se AS (SELECT (COUNT(*)=0) AS ALL_ACCT FROM scope)
    SELECT u.ORGANIZATION_NAME, u.CONTRACT_NUMBER, u.ACCOUNT_NAME, u.ACCOUNT_LOCATOR, u.REGION,
           u.ACCOUNT_LOCATOR || ''|'' || u.REGION AS ACCOUNT_KEY, u.SERVICE_LEVEL,
           u.USAGE_DATE AS USAGE_DATE_UTC, u.SERVICE_TYPE, u.USAGE_TYPE, u.RATING_TYPE,
           u.BILLING_TYPE, u.BALANCE_SOURCE, u.CURRENCY, u.IS_ADJUSTMENT,
           CASE WHEN u.IS_ADJUSTMENT THEN 0 ELSE u.USAGE END             AS USAGE_QTY,
           CASE WHEN u.IS_ADJUSTMENT THEN 0 ELSE u.USAGE_IN_CURRENCY END AS USAGE_IN_CURRENCY,
           CASE WHEN u.IS_ADJUSTMENT THEN u.USAGE_IN_CURRENCY ELSE 0 END AS ADJUSTMENT_IN_CURRENCY,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ORGANIZATION_USAGE.USAGE_IN_CURRENCY_DAILY u CROSS JOIN se
    WHERE u.USAGE_DATE >= DATEADD(''day'', -:retention, CURRENT_DATE())
      AND (se.ALL_ACCT OR u.ACCOUNT_NAME IN (SELECT ACCOUNT_NAME FROM scope));

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ORG_METERING_DAILY AS
    WITH scope AS (SELECT ACCOUNT_NAME FROM SF360.CONFIG.ACCOUNT_SCOPE WHERE IS_INCLUDED),
         se AS (SELECT (COUNT(*)=0) AS ALL_ACCT FROM scope)
    SELECT m.ORGANIZATION_NAME, m.ACCOUNT_NAME, m.ACCOUNT_LOCATOR, m.REGION,
           m.ACCOUNT_LOCATOR || ''|'' || m.REGION AS ACCOUNT_KEY,
           m.USAGE_DATE AS USAGE_DATE_UTC, m.SERVICE_TYPE,
           SUM(m.CREDITS_USED_COMPUTE) AS CREDITS_USED_COMPUTE,
           SUM(m.CREDITS_USED_CLOUD_SERVICES) AS CREDITS_USED_CLOUD_SERVICES,
           SUM(m.CREDITS_USED) AS CREDITS_USED,
           SUM(m.CREDITS_ADJUSTMENT_CLOUD_SERVICES) AS CREDITS_ADJUSTMENT_CLOUD_SERVICES,
           SUM(m.CREDITS_BILLED) AS CREDITS_BILLED, CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ORGANIZATION_USAGE.METERING_DAILY_HISTORY m CROSS JOIN se
    WHERE m.USAGE_DATE >= DATEADD(''day'', -:retention, CURRENT_DATE())
      AND (se.ALL_ACCT OR m.ACCOUNT_NAME IN (SELECT ACCOUNT_NAME FROM scope))
    GROUP BY 1,2,3,4,5,6,7;

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ORG_REMAINING_BALANCE AS
    SELECT ORGANIZATION_NAME, CONTRACT_NUMBER, DATE AS BALANCE_DATE, CURRENCY,
           FREE_USAGE_BALANCE, CAPACITY_BALANCE, ON_DEMAND_CONSUMPTION_BALANCE,
           ROLLOVER_BALANCE, MARKETPLACE_CAPACITY_DRAWDOWN_BALANCE,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ORGANIZATION_USAGE.REMAINING_BALANCE_DAILY
    WHERE DATE >= DATEADD(''day'', -:retention, CURRENT_DATE());

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ORG_ANOMALIES AS
    WITH scope AS (SELECT ACCOUNT_NAME FROM SF360.CONFIG.ACCOUNT_SCOPE WHERE IS_INCLUDED),
         se AS (SELECT (COUNT(*)=0) AS ALL_ACCT FROM scope)
    SELECT a.DATE AS ANOMALY_DATE, a.ANOMALY_ID, a.IS_ANOMALY, a.ORGANIZATION_NAME,
           a.ACCOUNT_NAME, a.ACCOUNT_LOCATOR, a.REGION,
           a.ACCOUNT_LOCATOR || ''|'' || a.REGION AS ACCOUNT_KEY, a.CURRENCY, a.ACTUAL_VALUE,
           GREATEST(a.FORECASTED_VALUE,0) AS FORECASTED_VALUE_FLOORED,
           a.FORECASTED_VALUE AS FORECASTED_VALUE_RAW,
           GREATEST(a.LOWER_BOUND,0) AS LOWER_BOUND_FLOORED, a.UPPER_BOUND,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ORGANIZATION_USAGE.ANOMALIES_IN_CURRENCY_DAILY a CROSS JOIN se
    WHERE a.DATE >= DATEADD(''day'', -:retention, CURRENT_DATE())
      AND (se.ALL_ACCT OR a.ACCOUNT_NAME IN (SELECT ACCOUNT_NAME FROM scope));

  msg := msg || ''org history ok; '';
  RETURN msg || ''SP_REBUILD_LANDING complete'';
END;
';
CREATE OR REPLACE PROCEDURE SF360.LANDING.SP_REBUILD_LANDING_ACCOUNT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
DECLARE
  retention NUMBER;
BEGIN
  ALTER SESSION SET TIMEZONE = ''UTC'';
  SELECT TO_NUMBER(SETTING_VALUE) INTO :retention
    FROM SF360.CONFIG.SETTINGS WHERE SETTING_KEY = ''RETENTION_DAYS'';

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_METERING_DAILY AS
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, USAGE_DATE AS USAGE_DATE_UTC, SERVICE_TYPE,
           SUM(CREDITS_USED_COMPUTE) AS CREDITS_USED_COMPUTE,
           SUM(CREDITS_USED_CLOUD_SERVICES) AS CREDITS_USED_CLOUD_SERVICES,
           SUM(CREDITS_USED) AS CREDITS_USED,
           SUM(CREDITS_ADJUSTMENT_CLOUD_SERVICES) AS CREDITS_ADJUSTMENT_CLOUD_SERVICES,
           SUM(CREDITS_BILLED) AS CREDITS_BILLED, CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ACCOUNT_USAGE.METERING_DAILY_HISTORY
    WHERE USAGE_DATE >= DATEADD(''day'', -:retention, CURRENT_DATE())
    GROUP BY 1,2,3;

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_WAREHOUSE_METERING AS
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, WAREHOUSE_ID, WAREHOUSE_NAME,
           START_TIME::DATE AS USAGE_DATE_UTC,
           SUM(CREDITS_USED_COMPUTE) AS CREDITS_USED_COMPUTE,
           SUM(CREDITS_USED_CLOUD_SERVICES) AS CREDITS_USED_CLOUD_SERVICES,
           SUM(CREDITS_USED) AS CREDITS_USED, COUNT(*) AS METERING_HOURS,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ACCOUNT_USAGE.WAREHOUSE_METERING_HISTORY
    WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
    GROUP BY 1,2,3,4;

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_QUERY_ATTRIBUTION AS
    WITH attr AS (
      SELECT QUERY_ID, PARENT_QUERY_ID, ROOT_QUERY_ID, WAREHOUSE_ID, WAREHOUSE_NAME,
             QUERY_TAG, USER_NAME, START_TIME, END_TIME,
             CREDITS_ATTRIBUTED_COMPUTE, CREDITS_USED_QUERY_ACCELERATION
      FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_ATTRIBUTION_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
    ),
    qh AS (
      SELECT QUERY_ID, ROLE_NAME, DATABASE_NAME, SCHEMA_NAME, QUERY_TYPE, EXECUTION_STATUS,
             WAREHOUSE_SIZE, BYTES_SCANNED, TOTAL_ELAPSED_TIME, EXECUTION_TIME,
             QUEUED_OVERLOAD_TIME, BYTES_SPILLED_TO_LOCAL_STORAGE, BYTES_SPILLED_TO_REMOTE_STORAGE
      FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
    )
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, a.START_TIME::DATE AS USAGE_DATE_UTC,
           a.QUERY_ID, a.PARENT_QUERY_ID, COALESCE(a.ROOT_QUERY_ID, a.QUERY_ID) AS ROOT_QUERY_ID,
           a.WAREHOUSE_ID, a.WAREHOUSE_NAME, a.USER_NAME, q.ROLE_NAME, q.DATABASE_NAME,
           q.SCHEMA_NAME, q.QUERY_TYPE, q.EXECUTION_STATUS, q.WAREHOUSE_SIZE, a.QUERY_TAG,
           a.START_TIME, a.END_TIME, a.CREDITS_ATTRIBUTED_COMPUTE,
           a.CREDITS_USED_QUERY_ACCELERATION, q.BYTES_SCANNED, q.TOTAL_ELAPSED_TIME,
           q.EXECUTION_TIME, q.QUEUED_OVERLOAD_TIME, q.BYTES_SPILLED_TO_LOCAL_STORAGE,
           q.BYTES_SPILLED_TO_REMOTE_STORAGE, CURRENT_TIMESTAMP() AS LOADED_AT
    FROM attr a LEFT JOIN qh q ON q.QUERY_ID = a.QUERY_ID;

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_ACCT_ANOMALIES AS
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, DATE AS ANOMALY_DATE, ANOMALY_ID, IS_ANOMALY,
           ACTUAL_VALUE, GREATEST(FORECASTED_VALUE,0) AS FORECASTED_VALUE_FLOORED,
           FORECASTED_VALUE AS FORECASTED_VALUE_RAW,
           GREATEST(LOWER_BOUND,0) AS LOWER_BOUND_FLOORED, UPPER_BOUND,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ACCOUNT_USAGE.ANOMALIES_DAILY
    WHERE DATE >= DATEADD(''day'', -:retention, CURRENT_DATE());

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_QUERY_INSIGHTS AS
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, START_TIME, END_TIME, TOTAL_ELAPSED_TIME,
           QUERY_ID, QUERY_HASH, QUERY_PARAMETERIZED_HASH, WAREHOUSE_ID, WAREHOUSE_NAME,
           INSIGHT_INSTANCE_ID, INSIGHT_TYPE_ID, INSIGHT_TOPIC, IS_OPPORTUNITY,
           MESSAGE, SUGGESTIONS, CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_INSIGHTS
    WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE());

