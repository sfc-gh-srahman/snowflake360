-- Snowflake360 :: LANDING schema, scripted from the live account.
--
-- Captured as a baseline because these objects were created ad hoc during
-- development and their definitions existed only inside the account. This file
-- is the reproducible record; the numbered files in sql/ remain the source of
-- truth for anything created after it.
--
-- Originally scripted from a live SF360 deployment, then hand-corrected.
--
-- Four tables that this file used to build were removed after an audit found that
-- nothing read them: LND_ORG_CONTRACT_ITEMS, LND_STORAGE_DAILY,
-- LND_WAREHOUSE_EVENTS_DAILY and LND_WAREHOUSE_LOAD_DAILY. They were built on
-- every nightly run and granted to SF360_APP_ROLE, but no page, no curated object
-- and no procedure referenced any of them -- they were landed during development
-- for panels that were ultimately built from other sources. Storage in particular
-- still reaches the app: it arrives as SERVICE_TYPE 'STORAGE' through
-- LND_ORG_CURRENCY_DAILY into FCT_DAILY_CURRENCY, which is what the Consumption
-- and Usage pages read.
--
-- CREATE OR REPLACE is correct in this schema, unlike in CONFIG. Everything here
-- is a projection of SNOWFLAKE.ACCOUNT_USAGE / ORGANIZATION_USAGE and is rebuilt
-- in full nightly, because those views back-fill late-arriving rows and a
-- trailing-window incremental load would silently miss them.

