CREATE OR REPLACE PROCEDURE SF360.LANDING.SP_REBUILD_LANDING_ACCOUNT2()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
DECLARE
  retention NUMBER;
BEGIN
  ALTER SESSION SET TIMEZONE = ''UTC'';
  SELECT TO_NUMBER(SETTING_VALUE) INTO :retention
    FROM SF360.CONFIG.SETTINGS WHERE SETTING_KEY = ''RETENTION_DAYS'';

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_QUERY_DAILY AS
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, START_TIME::DATE AS USAGE_DATE_UTC,
           WAREHOUSE_NAME, WAREHOUSE_SIZE, USER_NAME, ROLE_NAME, QUERY_TYPE, EXECUTION_STATUS,
           COUNT(*) AS QUERY_COUNT,
           COUNT_IF(EXECUTION_STATUS=''SUCCESS'') AS QUERY_COUNT_SUCCESS,
           SUM(BYTES_SCANNED) AS BYTES_SCANNED, SUM(ROWS_PRODUCED) AS ROWS_PRODUCED,
           SUM(TOTAL_ELAPSED_TIME) AS TOTAL_ELAPSED_MS, SUM(EXECUTION_TIME) AS EXECUTION_MS,
           SUM(QUEUED_OVERLOAD_TIME) AS QUEUED_OVERLOAD_MS, SUM(COMPILATION_TIME) AS COMPILATION_MS,
           SUM(BYTES_SPILLED_TO_LOCAL_STORAGE) AS SPILL_LOCAL_BYTES,
           SUM(BYTES_SPILLED_TO_REMOTE_STORAGE) AS SPILL_REMOTE_BYTES,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
    WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
    GROUP BY 1,2,3,4,5,6,7,8;

  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_DATA_TRANSFER_DAILY AS
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, START_TIME::DATE AS USAGE_DATE_UTC,
           TRANSFER_TYPE, SOURCE_CLOUD, SOURCE_REGION, TARGET_CLOUD, TARGET_REGION,
           SUM(BYTES_TRANSFERRED) AS BYTES_TRANSFERRED,
           SUM(BYTES_TRANSFERRED)/POWER(1024,4) AS TB_TRANSFERRED,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM SNOWFLAKE.ACCOUNT_USAGE.DATA_TRANSFER_HISTORY
    WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
    GROUP BY 1,2,3,4,5,6,7;

  -- SHARES.TARGET_ACCOUNTS and LISTINGS.TARGETS are different semi-structured types,
  -- so both are cast to VARCHAR before the union.
  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_SHARING_INVENTORY AS
    WITH shares AS (
      SELECT ''SHARE''::VARCHAR AS OBJECT_KIND, NAME::VARCHAR AS OBJECT_NAME,
             DATABASE_NAME::VARCHAR AS OBJECT_DETAIL, OWNER::VARCHAR AS OWNER_NAME,
             TO_VARCHAR(TARGET_ACCOUNTS) AS TARGET_ACCOUNTS,
             LISTING_GLOBAL_NAME::VARCHAR AS LISTING_GLOBAL_NAME,
             NULL::VARCHAR AS STATE, CREATED_ON::DATE AS CREATED_DATE,
             DELETED_ON::DATE AS DELETED_DATE
      FROM SNOWFLAKE.ACCOUNT_USAGE.SHARES
    ),
    listings AS (
      SELECT ''LISTING''::VARCHAR, COALESCE(TITLE, NAME)::VARCHAR, SHARE::VARCHAR,
             OWNER::VARCHAR, TO_VARCHAR(TARGETS), GLOBAL_NAME::VARCHAR,
             STATE::VARCHAR, CREATED_ON::DATE, DELETED_ON::DATE
      FROM SNOWFLAKE.ACCOUNT_USAGE.LISTINGS
    )
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, s.*, CURRENT_TIMESTAMP() AS LOADED_AT
    FROM (SELECT * FROM shares UNION ALL SELECT * FROM listings) s;

  RETURN ''SP_REBUILD_LANDING_ACCOUNT2 complete'';
END;
';
CREATE OR REPLACE PROCEDURE SF360.LANDING.SP_REBUILD_LANDING_AI()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS CALLER
AS '
DECLARE
  retention NUMBER;
BEGIN
  ALTER SESSION SET TIMEZONE = ''UTC'';
  SELECT TO_NUMBER(SETTING_VALUE) INTO :retention
    FROM SF360.CONFIG.SETTINGS WHERE SETTING_KEY = ''RETENTION_DAYS'';

  -- Three verified overlap traps are handled here:
  --  1. SNOWFLAKE_COCO_USAGE_HISTORY spans full history and supersedes the three legacy
  --     CORTEX_CODE_* views (identical counts, 3318 shared REQUEST_IDs).
  --  2. CORTEX_AISQL overlaps CORTEX_AI_FUNCTIONS on 667 of 669 QUERY_IDs.
  --  3. SNOWFLAKE_INTELLIGENCE and SNOWFLAKE_COWORK are byte-identical (same REQUEST_IDs).
  CREATE OR REPLACE TRANSIENT TABLE SF360.LANDING.LND_AI_USAGE_DAILY AS
    WITH aif AS (
      SELECT START_TIME, FUNCTION_NAME, MODEL_NAME, CREDITS, QUERY_ID
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AI_FUNCTIONS_USAGE_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
    ),
    aif_ids AS (SELECT DISTINCT QUERY_ID FROM aif WHERE QUERY_ID IS NOT NULL),
    aisql_dedup AS (
      SELECT s.USAGE_TIME, s.FUNCTION_NAME, s.MODEL_NAME, s.TOKEN_CREDITS, s.TOKENS
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AISQL_USAGE_HISTORY s
      LEFT JOIN aif_ids i ON i.QUERY_ID = s.QUERY_ID
      WHERE s.USAGE_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE()) AND i.QUERY_ID IS NULL
    ),
    u AS (
      SELECT START_TIME::DATE AS D, ''AI Functions'' AS FEATURE, FUNCTION_NAME AS SUB_FEATURE,
             MODEL_NAME, NULL::VARCHAR AS USER_NAME, CREDITS, NULL::NUMBER AS TOKENS
      FROM aif
      UNION ALL
      SELECT USAGE_TIME::DATE, ''AI Functions'', FUNCTION_NAME, MODEL_NAME, NULL, TOKEN_CREDITS, TOKENS
      FROM aisql_dedup
      UNION ALL
      SELECT START_TIME::DATE, ''Cortex Agents'', AGENT_NAME, NULL, USER_NAME, TOKEN_CREDITS, TOKENS
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_AGENT_USAGE_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
      UNION ALL
      SELECT START_TIME::DATE, ''Cortex Search'', SERVICE_NAME, NULL, NULL, CREDITS, NULL
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_SEARCH_SERVING_USAGE_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
      UNION ALL
      SELECT START_TIME::DATE, ''Cortex Analyst'', NULL, NULL, USERNAME, CREDITS, NULL
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_ANALYST_USAGE_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
      UNION ALL
      SELECT START_TIME::DATE, ''Document Processing'', FUNCTION_NAME, MODEL_NAME, NULL, CREDITS_USED, NULL
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_DOCUMENT_PROCESSING_USAGE_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
      UNION ALL
      SELECT USAGE_TIME::DATE, ''Cortex Code'', INTERFACE, NULL, USER_NAME, TOKEN_CREDITS, TOKENS
      FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COCO_USAGE_HISTORY
      WHERE USAGE_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
      UNION ALL
      SELECT START_TIME::DATE, ''CoWork'', SNOWFLAKE_COWORK_NAME, NULL, USER_NAME, TOKEN_CREDITS, TOKENS
      FROM SNOWFLAKE.ACCOUNT_USAGE.SNOWFLAKE_COWORK_USAGE_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
      UNION ALL
      SELECT START_TIME::DATE, ''Cortex REST API'', NULL, MODEL_NAME, NULL, 0, TOKENS
      FROM SNOWFLAKE.ACCOUNT_USAGE.CORTEX_REST_API_USAGE_HISTORY
      WHERE START_TIME >= DATEADD(''day'', -:retention, CURRENT_DATE())
    )
    SELECT CURRENT_ACCOUNT_NAME() AS ACCOUNT_NAME, D AS USAGE_DATE_UTC, FEATURE,
           COALESCE(SUB_FEATURE,''n/a'') AS SUB_FEATURE,
           COALESCE(MODEL_NAME,''n/a'')  AS MODEL_NAME,
           COALESCE(USER_NAME,''UNKNOWN'') AS USER_NAME,
           SUM(COALESCE(CREDITS,0)) AS CREDITS,
           SUM(COALESCE(TOKENS,0))  AS TOKENS,
           COUNT(*) AS EVENT_COUNT,
           CURRENT_TIMESTAMP() AS LOADED_AT
    FROM u GROUP BY 1,2,3,4,5,6;

  RETURN ''SP_REBUILD_LANDING_AI complete'';
END;
';

